package expo.modules.medchainalarm

import android.content.Context
import org.json.JSONObject

/** One alarm, persisted natively so it can be re-armed after a reboot without any JavaScript. */
data class StoredAlarm(
  val id: String,
  val triggerAtMillis: Long,
  val occurrenceId: String,
  val medicationId: String,
  val title: String,
  val body: String,
  val soundEnabled: Boolean,
  val vibrationEnabled: Boolean,
  /** Sound key from Settings, e.g. "signature_female" -> res/raw/medchain_reminder_signature_female. */
  val voice: String = "female",
  /** Structured details for the alarm screen; empty for alarms armed by older app versions. */
  val medicationName: String = "",
  val dosageText: String = "",
  val instructions: String = "",
  /** The dose's own scheduled time; triggerAtMillis is the snooze time after a snooze. 0 = unknown. */
  val scheduledAtMillis: Long = 0L
) {
  fun displayTimeMillis(): Long = if (scheduledAtMillis > 0) scheduledAtMillis else triggerAtMillis

  /** Medicine name for display, falling back to the notification title. */
  fun displayName(): String = medicationName.ifBlank { title.removePrefix("Medication Reminder:").trim().ifBlank { title } }

  fun toJson(): String = JSONObject().apply {
    put("id", id)
    put("triggerAtMillis", triggerAtMillis)
    put("occurrenceId", occurrenceId)
    put("medicationId", medicationId)
    put("title", title)
    put("body", body)
    put("soundEnabled", soundEnabled)
    put("vibrationEnabled", vibrationEnabled)
    put("voice", voice)
    put("medicationName", medicationName)
    put("dosageText", dosageText)
    put("instructions", instructions)
    put("scheduledAtMillis", scheduledAtMillis)
  }.toString()

  companion object {
    fun fromJson(raw: String): StoredAlarm? = try {
      val o = JSONObject(raw)
      StoredAlarm(
        o.getString("id"),
        o.getLong("triggerAtMillis"),
        o.getString("occurrenceId"),
        o.getString("medicationId"),
        o.getString("title"),
        o.getString("body"),
        o.optBoolean("soundEnabled", true),
        o.optBoolean("vibrationEnabled", true),
        o.optString("voice", "female"),
        o.optString("medicationName", ""),
        o.optString("dosageText", ""),
        o.optString("instructions", ""),
        o.optLong("scheduledAtMillis", 0L)
      )
    } catch (e: Exception) {
      null
    }
  }
}

object AlarmStore {
  private const val PREFS = "medchain_alarms"
  private const val NEEDS_RECONCILE = "needs_reconcile"

  private fun prefs(c: Context) = c.getSharedPreferences(PREFS, Context.MODE_PRIVATE)

  fun put(c: Context, a: StoredAlarm) {
    prefs(c).edit().putString("alarm_" + a.id, a.toJson()).apply()
  }

  fun remove(c: Context, id: String) {
    prefs(c).edit().remove("alarm_$id").apply()
  }

  fun get(c: Context, id: String): StoredAlarm? =
    prefs(c).getString("alarm_$id", null)?.let { StoredAlarm.fromJson(it) }

  fun all(c: Context): List<StoredAlarm> =
    prefs(c).all.entries
      .filter { it.key.startsWith("alarm_") }
      .mapNotNull { (it.value as? String)?.let { raw -> StoredAlarm.fromJson(raw) } }
      .sortedBy { it.triggerAtMillis }

  fun clear(c: Context) {
    val e = prefs(c).edit()
    prefs(c).all.keys.filter { it.startsWith("alarm_") }.forEach { e.remove(it) }
    e.apply()
  }

  /** Set when the clock or time zone changed: local-time schedules must be regenerated by the app. */
  fun setNeedsReconcile(c: Context, v: Boolean) {
    prefs(c).edit().putBoolean(NEEDS_RECONCILE, v).apply()
  }

  fun consumeNeedsReconcile(c: Context): Boolean {
    val v = prefs(c).getBoolean(NEEDS_RECONCILE, false)
    if (v) setNeedsReconcile(c, false)
    return v
  }
}
